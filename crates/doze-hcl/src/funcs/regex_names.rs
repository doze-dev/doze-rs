/// Go's `canonicalName`: `_`, `-` and spaces dropped, the first letter upper case, the rest lower.
fn canonical(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut first = true;
    for c in name.chars() {
        match c {
            '_' | '-' | ' ' => {}
            c if first => {
                out.push(c.to_ascii_uppercase());
                first = false;
            }
            c => out.push(c.to_ascii_lowercase()),
        }
    }
    out
}

/// The `regex` crate's name for a class Go knows by `name`, or `None` if Go does not know it.
pub(super) fn unicode_class(name: &str) -> Option<&'static str> {
    let c = canonical(name);
    match c.as_str() {
        "Any" => return Some("Any"),
        "Assigned" => return Some("Assigned"),
        "Ascii" => return Some("ASCII"),
        "Lc" => return Some("LC"),
        _ => {}
    }
    if let Some(cat) = CATEGORIES.iter().find(|k| **k == c) {
        return Some(cat);
    }
    if let Some(s) = SCRIPTS.iter().find(|s| canonical(s) == c) {
        return Some(s);
    }
    CATEGORY_ALIASES
        .iter()
        .find(|(alias, _)| canonical(alias) == c)
        .map(|(_, cat)| *cat)
}
