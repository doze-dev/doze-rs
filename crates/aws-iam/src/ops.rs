impl Core {
    pub(crate) fn run_iam(&mut self, op: u32, r: &Req<'_>) -> Result<Value, ApiError> {
        let Some(op) = Op::from_index(op).filter(|op| BUILT.contains(op)) else {
            return Err(ApiError::new(
                501,
                "NotImplemented",
                "This operation is not built in doze-aws.",
            ));
        };
        match op {
            Op::CreateUser => self.create_entity(User, r),
            Op::GetUser => self.get_user_or_caller(r),
            Op::UpdateUser => self.update_named(User, r),
            Op::DeleteUser => self.delete_entity(User, r),
            Op::ListUsers => self.list_entities(User, r),
            Op::TagUser => self.tag_entity(User, r),
            Op::UntagUser => self.untag_entity(User, r),
            Op::ListUserTags => self.list_entity_tags(User, r),
            Op::CreateGroup => self.create_entity(Group, r),
            Op::GetGroup => self.get_group(r),
            Op::UpdateGroup => self.update_named(Group, r),
            Op::DeleteGroup => self.delete_entity(Group, r),
            Op::ListGroups => self.list_entities(Group, r),
            Op::AddUserToGroup => self.add_user_to_group(r),
            Op::RemoveUserFromGroup => self.remove_user_from_group(r),
            Op::ListGroupsForUser => self.list_groups_for_user(r),
            Op::CreateRole => self.create_entity(Role, r),
            Op::GetRole => self.get_entity(Role, r),
            Op::UpdateRole => self.update_role(r),
            Op::UpdateRoleDescription => self.update_role_description(r),
            Op::DeleteRole => self.delete_entity(Role, r),
            Op::ListRoles => self.list_entities(Role, r),
            Op::UpdateAssumeRolePolicy => self.update_assume_role_policy(r),
            Op::TagRole => self.tag_entity(Role, r),
            Op::UntagRole => self.untag_entity(Role, r),
            Op::ListRoleTags => self.list_entity_tags(Role, r),
            Op::CreateServiceLinkedRole => self.create_service_linked_role(r),
            Op::DeleteServiceLinkedRole => self.delete_service_linked_role(r),
            Op::GetServiceLinkedRoleDeletionStatus => {
                Ok(self.service_linked_role_deletion_status())
            }
            _ => self.run_policies(op, r),
        }
    }

    /// The policy, key, profile and account operations.
    fn run_policies(&mut self, op: Op, r: &Req<'_>) -> Result<Value, ApiError> {
        match op {
            Op::CreatePolicy => self.create_policy(r),
            Op::GetPolicy => self.get_policy(r),
            Op::DeletePolicy => self.delete_policy(r),
            Op::ListPolicies => self.list_policies(r),
            Op::CreatePolicyVersion => self.create_policy_version(r),
            Op::GetPolicyVersion => self.get_policy_version(r),
            Op::DeletePolicyVersion => self.delete_policy_version(r),
            Op::ListPolicyVersions => self.list_policy_versions(r),
            Op::SetDefaultPolicyVersion => self.set_default_policy_version(r),
            Op::TagPolicy => self.tag_policy(r),
            Op::UntagPolicy => self.untag_policy(r),
            Op::ListPolicyTags => self.list_policy_tags(r),
            Op::ListEntitiesForPolicy => self.list_entities_for_policy(r),
            Op::AttachUserPolicy => self.attach(User, r),
            Op::DetachUserPolicy => self.detach(User, r),
            Op::AttachGroupPolicy => self.attach(Group, r),
            Op::DetachGroupPolicy => self.detach(Group, r),
            Op::AttachRolePolicy => self.attach(Role, r),
            Op::DetachRolePolicy => self.detach(Role, r),
            Op::ListAttachedUserPolicies => self.list_attached(User, r),
            Op::ListAttachedGroupPolicies => self.list_attached(Group, r),
            Op::ListAttachedRolePolicies => self.list_attached(Role, r),
            Op::PutUserPolicy => self.put_inline(User, r),
            Op::GetUserPolicy => self.get_inline(User, r),
            Op::DeleteUserPolicy => self.delete_inline(User, r),
            Op::ListUserPolicies => self.list_inline(User, r),
            Op::PutGroupPolicy => self.put_inline(Group, r),
            Op::GetGroupPolicy => self.get_inline(Group, r),
            Op::DeleteGroupPolicy => self.delete_inline(Group, r),
            Op::ListGroupPolicies => self.list_inline(Group, r),
            Op::PutRolePolicy => self.put_inline(Role, r),
            Op::GetRolePolicy => self.get_inline(Role, r),
            Op::DeleteRolePolicy => self.delete_inline(Role, r),
            Op::ListRolePolicies => self.list_inline(Role, r),
            Op::PutUserPermissionsBoundary => self.put_boundary(User, r),
            Op::DeleteUserPermissionsBoundary => self.delete_boundary(User, r),
            Op::PutRolePermissionsBoundary => self.put_boundary(Role, r),
            Op::DeleteRolePermissionsBoundary => self.delete_boundary(Role, r),
            _ => self.run_rest(op, r),
        }
    }

    /// Keys, profiles, and the account and its providers.
    fn run_rest(&mut self, op: Op, r: &Req<'_>) -> Result<Value, ApiError> {
        match op {
            Op::SimulateCustomPolicy => self.simulate_custom(r),
            Op::SimulatePrincipalPolicy => self.simulate_principal(r),
            Op::GetContextKeysForCustomPolicy => self.context_keys_custom(r),
            Op::GetContextKeysForPrincipalPolicy => self.context_keys_principal(r),
            Op::CreateAccessKey => self.create_access_key(r),
            Op::ListAccessKeys => self.list_access_keys(r),
            Op::UpdateAccessKey => self.update_access_key(r),
            Op::DeleteAccessKey => self.delete_access_key(r),
            Op::GetAccessKeyLastUsed => self.get_access_key_last_used(r),
            Op::CreateInstanceProfile => self.create_instance_profile(r),
            Op::GetInstanceProfile => self.get_instance_profile(r),
            Op::DeleteInstanceProfile => self.delete_instance_profile(r),
            Op::ListInstanceProfiles => self.list_instance_profiles(r),
            Op::ListInstanceProfilesForRole => self.list_instance_profiles_for_role(r),
            Op::AddRoleToInstanceProfile => self.add_role_to_instance_profile(r),
            Op::RemoveRoleFromInstanceProfile => self.remove_role_from_instance_profile(r),
            Op::TagInstanceProfile => self.tag_profile(r),
            Op::UntagInstanceProfile => self.untag_profile(r),
            Op::ListInstanceProfileTags => self.list_profile_tags(r),
            Op::CreateAccountAlias => self.create_account_alias(r),
            Op::DeleteAccountAlias => self.delete_account_alias(r),
            Op::ListAccountAliases => self.list_account_aliases(r),
            Op::GetAccountSummary => Ok(self.get_account_summary()),
            Op::UpdateAccountPasswordPolicy => self.update_password_policy(r),
            Op::GetAccountPasswordPolicy => self.get_password_policy(r),
            Op::DeleteAccountPasswordPolicy => self.delete_password_policy(r),
            Op::CreateLoginProfile => self.create_login_profile(r),
            Op::GetLoginProfile => self.get_login_profile(r),
            Op::UpdateLoginProfile => self.update_login_profile(r),
            Op::DeleteLoginProfile => self.delete_login_profile(r),
            _ => self.run_providers(op, r),
        }
    }

    fn run_providers(&mut self, op: Op, r: &Req<'_>) -> Result<Value, ApiError> {
        const OIDC: &str = "OpenIDConnectProviderArn";
        const SAML: &str = "SAMLProviderArn";
        match op {
            Op::CreateOpenIDConnectProvider => self.create_oidc_provider(r),
            Op::GetOpenIDConnectProvider => self.get_oidc_provider(r),
            Op::ListOpenIDConnectProviders => Ok(self.list_providers(false)),
            Op::DeleteOpenIDConnectProvider => self.delete_provider(r, false),
            Op::AddClientIDToOpenIDConnectProvider => self.add_client_id(r),
            Op::RemoveClientIDFromOpenIDConnectProvider => self.remove_client_id(r),
            Op::UpdateOpenIDConnectProviderThumbprint => self.update_thumbprint(r),
            Op::TagOpenIDConnectProvider => self.tag_provider(r, OIDC, false),
            Op::UntagOpenIDConnectProvider => self.untag_provider(r, OIDC, false),
            Op::ListOpenIDConnectProviderTags => self.list_provider_tags(r, OIDC, false),
            Op::CreateSAMLProvider => self.create_saml_provider(r),
            Op::GetSAMLProvider => self.get_saml_provider(r),
            Op::ListSAMLProviders => Ok(self.list_providers(true)),
            Op::DeleteSAMLProvider => self.delete_provider(r, true),
            Op::UpdateSAMLProvider => self.update_saml_provider(r),
            Op::TagSAMLProvider => self.tag_provider(r, SAML, true),
            Op::UntagSAMLProvider => self.untag_provider(r, SAML, true),
            Op::ListSAMLProviderTags => self.list_provider_tags(r, SAML, true),
            _ => Err(ApiError::new(
                501,
                "NotImplemented",
                "This operation is not built in doze-aws.",
            )),
        }
    }
}
