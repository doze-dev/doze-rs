// Refreshes public_suffix_list.fc, doze-config's embedded copy of the public suffix list.
//
//   bun crates/doze-config/data/refresh-psl.ts            # from publicsuffix.org
//   bun crates/doze-config/data/refresh-psl.ts list.dat   # from a file already downloaded
//
// The rules are read as Go's golang.org/x/net/publicsuffix/gen.go reads them: lines trimmed, `//`
// comments and blank lines skipped, the ICANN section told from the private one by its markers,
// and non-ASCII labels turned into punycode (Go's table holds ASCII only, so a Unicode name never
// matches a rule there either).
//
// The output is front-coded to keep the binary small (src/psl.rs decodes it on the first lookup):
// each rule's labels are reversed (`*.kawasaki.jp` is `jp.kawasaki.*`), the rules of a section are
// sorted, and each line is one base-36 digit (how many leading bytes it shares with the line before,
// at most 35) followed by the rest.
//
// After a refresh, bump the `psl` dev-dependency in crates/doze-config/Cargo.toml to a release built
// from the same list: tests/psl.rs compares every rule against it.
import { domainToASCII } from "node:url";

const SOURCE = "https://publicsuffix.org/list/public_suffix_list.dat";
const OUT = new URL("./public_suffix_list.fc", import.meta.url);
const VALID = /^[a-z0-9_!*\-.]+$/;

const arg = process.argv[2];
const text = arg ? await Bun.file(arg).text() : await fetchList();

const version = text.match(/^\/\/ VERSION: (\S+)$/m)?.[1];
const commit = text.match(/^\/\/ COMMIT: ([0-9a-f]{40})$/m)?.[1];
if (!version || !commit) throw new Error("the list has no VERSION or COMMIT line");

const sections: Record<"icann" | "private", string[]> = { icann: [], private: [] };
let section: "icann" | "private" | null = null;
for (const raw of text.split("\n")) {
  const line = raw.trim();
  if (line.includes("BEGIN ICANN DOMAINS")) section = "icann";
  else if (line.includes("END ICANN DOMAINS")) section = null;
  else if (line.includes("BEGIN PRIVATE DOMAINS")) section = "private";
  else if (line.includes("END PRIVATE DOMAINS")) section = null;
  else if (line !== "" && !line.startsWith("//")) {
    // Go puts rules outside the markers in the private section (icann is false there).
    sections[section ?? "private"].push(ascii(line));
  }
}

const body = (["icann", "private"] as const)
  .map((name) => `=${name}\n${frontCode(sections[name])}`)
  .join("");
const header = [
  "// The public suffix list, front-coded for doze-config. Generated by refresh-psl.ts; do not edit.",
  `// Source: ${SOURCE} (Mozilla Public License 2.0)`,
  `// VERSION: ${version}`,
  `// COMMIT: ${commit}`,
  `// Rules: ${sections.icann.length} ICANN, ${sections.private.length} private`,
  "",
].join("\n");
await Bun.write(OUT, header + body);
console.log(`wrote ${OUT.pathname}: ${version} ${commit}, ${(header + body).length} bytes`);

async function fetchList(): Promise<string> {
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`GET ${SOURCE}: ${res.status}`);
  return res.text();
}

function ascii(rule: string): string {
  const out = rule
    .split(".")
    .map((label) => (/^[\x00-\x7f]*$/.test(label) ? label : domainToASCII(label)))
    .join(".");
  if (!VALID.test(out)) throw new Error(`bad rule: ${JSON.stringify(rule)} -> ${JSON.stringify(out)}`);
  return out;
}

function frontCode(rules: string[]): string {
  const keys = [...new Set(rules.map((r) => r.split(".").reverse().join(".")))].sort((a, b) =>
    a < b ? -1 : a > b ? 1 : 0,
  );
  let prev = "";
  let out = "";
  for (const key of keys) {
    let n = 0;
    while (n < 35 && n < prev.length && n < key.length && prev[n] === key[n]) n++;
    out += n.toString(36) + key.slice(n) + "\n";
    prev = key;
  }
  return out;
}
