//! Which program owns /etc/resolv.conf, decided by the marker comment it writes there rather than by probing what is
//! running.
//!
//! That distinction is the one Tailscale arrived at the hard way: a machine can have systemd-resolved running while
//! something else entirely owns resolution, and asking the process table says the wrong thing. The file says who is in
//! charge, because whoever is in charge signs it.
//!
//! Plain text in, an answer out, so it is tested (and fuzzed) on every system, not only on Linux.

use std::fmt;
use std::path::Path;

/// What owns /etc/resolv.conf.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Manager {
    Unknown,
    Resolved,
    Resolvconf,
    NetworkManager,
    Plain,
}

impl fmt::Display for Manager {
    /// The words the setup report prints.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Manager::Resolved => "systemd-resolved",
            Manager::Resolvconf => "resolvconf",
            Manager::NetworkManager => "NetworkManager",
            Manager::Plain => "plain /etc/resolv.conf",
            Manager::Unknown => "unknown",
        })
    }
}

/// Classifies the text of a resolv.conf by the marker its writer leaves.
// fuzz:parser fuzz_setup
pub fn detect_from(text: &str) -> Manager {
    if text.contains("systemd-resolved") || text.contains("stub-resolv.conf") {
        Manager::Resolved
    } else if text.contains("Generated by resolvconf") {
        Manager::Resolvconf
    } else if text.contains("Generated by NetworkManager") {
        Manager::NetworkManager
    } else {
        Manager::Plain
    }
}

/// The manager of the resolv.conf at `path`; [`Manager::Unknown`] when it cannot be read.
pub fn detect(path: &Path) -> Manager {
    std::fs::read_to_string(path).map_or(Manager::Unknown, |t| detect_from(&t))
}

/// Whether this machine can send one domain to the doze resolver without doze becoming the resolver for everything
/// else. systemd-resolved does it natively; otherwise it takes a running dnsmasq. Plain NetworkManager cannot route by
/// domain and neither can a bare resolv.conf, so those machines get apex names from the hosts file and nothing more.
///
/// `dnsmasq` is passed, not probed, so the decision is a pure function of what was found: the caller does the looking.
pub fn can_route_domain(m: Manager, dnsmasq: bool) -> bool {
    m == Manager::Resolved || dnsmasq
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Go: TestDetectFrom. Real first lines, because the detection is exactly a string match against what each program
    /// writes and a paraphrase would prove nothing.
    #[test]
    fn the_marker_says_who_owns_resolv_conf() {
        let cases = [
            (
                "# This is /run/systemd/resolve/stub-resolv.conf managed by man:systemd-resolved(8).\n\
                 nameserver 127.0.0.53\noptions edns0 trust-ad\n",
                Manager::Resolved,
            ),
            (
                "# Generated by resolvconf\nnameserver 192.168.1.1\n",
                Manager::Resolvconf,
            ),
            (
                "# Generated by NetworkManager\nnameserver 192.168.1.1\n",
                Manager::NetworkManager,
            ),
            ("nameserver 8.8.8.8\nnameserver 1.1.1.1\n", Manager::Plain),
            ("", Manager::Plain),
        ];
        for (body, want) in cases {
            assert_eq!(detect_from(body), want, "{body:?}");
        }
    }

    /// Go: TestOnlySystemdResolvedRoutesADomainByItself. Getting this backwards would have doze quietly taking over
    /// resolution for everything.
    #[test]
    fn only_systemd_resolved_routes_a_domain_by_itself() {
        for m in [
            Manager::Resolvconf,
            Manager::NetworkManager,
            Manager::Plain,
            Manager::Unknown,
        ] {
            assert!(!can_route_domain(m, false), "{m} without dnsmasq");
            assert!(can_route_domain(m, true), "{m} with dnsmasq running");
        }
        assert!(can_route_domain(Manager::Resolved, false));
    }

    /// Go: TestManagerNames. These strings are printed to people in the setup report.
    #[test]
    fn manager_names_as_printed() {
        let names = [
            (Manager::Resolved, "systemd-resolved"),
            (Manager::Resolvconf, "resolvconf"),
            (Manager::NetworkManager, "NetworkManager"),
            (Manager::Plain, "plain /etc/resolv.conf"),
            (Manager::Unknown, "unknown"),
        ];
        for (m, want) in names {
            assert_eq!(m.to_string(), want);
        }
    }
}
