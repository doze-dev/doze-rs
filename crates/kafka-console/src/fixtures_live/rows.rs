//! The rows of the Live boards.
#![allow(clippy::too_many_lines, clippy::too_many_arguments)] // a table of the boards' rows

use super::{Spec, at, wr};
use crate::model::{WireClass, WireRow};

fn done(
    id: u64,
    time: &str,
    client: &str,
    tag: &str,
    api: &'static str,
    version: i16,
    target: &str,
    sub: Option<&str>,
    detail: &str,
    ms: u32,
) -> WireRow {
    wr(&Spec {
        id,
        time,
        client,
        tag,
        api,
        version,
        target,
        sub,
        class: WireClass::Done,
        code: 0,
        detail,
        took_ms: ms,
    })
}

