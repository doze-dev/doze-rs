#!/usr/bin/env bun
// Measures a doze-aws server against the AWS recordings in conformance/snapshots/, one module at a time, on a fresh server each.
//   GO_BIN=/path/to/doze-aws bun tools/aws-rec/baseline.ts [module ...]     (default: every module that has a recording)
//   or point at the Rust edition later:  SERVER_CMD='target/release/doze-aws --listen {addr} --data-dir {data}'
// Prints one line per module and writes docs/port/aws/baseline.md.
import { existsSync, mkdtempSync, readdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createServer } from "node:net";

const here = import.meta.dir;
const root = `${here}/../..`;
const conformance = `${root}/conformance`;
const UV = process.env.UV_BIN ?? `${process.env.HOME}/.proto/tools/uv/0.12.19/uv`;
const label = process.env.BASELINE_LABEL ?? "Go doze-aws (origin/main f8c31a1)";
const template = process.env.SERVER_CMD ?? (process.env.GO_BIN ? `${process.env.GO_BIN} --listen {addr} --data-dir {data}` : "");
if (!template) { console.error("set GO_BIN=/path/to/doze-aws or SERVER_CMD='... {addr} ... {data}'"); process.exit(2); }

const recorded = readdirSync(`${conformance}/snapshots`).filter((f) => /^test_.*\.json$/.test(f)).map((f) => f.slice(5, -5)).sort();
const modules = process.argv.slice(2).length ? process.argv.slice(2) : recorded;

const freePort = () => new Promise<number>((res) => { const s = createServer(); s.listen(0, "127.0.0.1", () => { const p = (s.address() as { port: number }).port; s.close(() => res(p)); }); });
const up = async (port: number) => { for (let i = 0; i < 100; i++) { try { const c = await Bun.connect({ hostname: "127.0.0.1", port, socket: { data() {}, open(s) { s.end(); } } }); c.end(); return true; } catch { await Bun.sleep(100); } } return false; };

type Row = { module: string; exact: number; other: number; unverified: number; textOnly: number; behavioural: number; note: string };
const rows: Row[] = [];

for (const m of modules) {
  if (!existsSync(`${conformance}/snapshots/test_${m}.json`)) { rows.push({ module: m, exact: 0, other: 0, unverified: 0, textOnly: 0, behavioural: 0, note: "no recording" }); continue; }
  const data = mkdtempSync(join(tmpdir(), "baseline-"));
  const port = await freePort();
  const cmd = template.replaceAll("{addr}", `127.0.0.1:${port}`).replaceAll("{data}", data).split(" ");
  const server = Bun.spawn(cmd, { cwd: data, stdout: "ignore", stderr: "ignore" });
  try {
    if (!(await up(port))) { rows.push({ module: m, exact: 0, other: 0, unverified: 0, textOnly: 0, behavioural: 0, note: "server did not start" }); continue; }
    const p = Bun.spawn([UV, "run", "--frozen", "pytest", `tests/test_${m}.py`, "-p", "no:cacheprovider"], {
      cwd: conformance, stdout: "pipe", stderr: "pipe", env: { ...process.env, CONFORMANCE_ENDPOINT: `http://127.0.0.1:${port}`, CONFORMANCE_TARGET: "doze" },
    });
    const text = (await new Response(p.stdout).text()) + (await new Response(p.stderr).text());
    await p.exited;
    const n = (re: RegExp) => Number(text.match(re)?.[1] ?? 0);
    const exact = n(/(\d+)\s+matched what real AWS answered/), other = n(/(\d+)\s+answered differently/), unverified = n(/(\d+)\s+UNVERIFIED/);
    // classify the differing labels: those whose only differing field is the error message text
    const byLabel = new Map<string, Set<string>>();
    let test = "", lab = "", path = "";
    for (const l of text.split("\n")) {
      let x;
      if ((x = l.match(/^_+ ERROR at teardown of (\S+) _+$/))) test = x[1];
      else if ((x = l.match(/^E {13}\[(.+)\]$/))) lab = x[1];
      else if ((x = l.match(/^E {15}(\$\S*)$/))) { path = x[1]; (byLabel.get(`${test}/${lab}`) ?? byLabel.set(`${test}/${lab}`, new Set()).get(`${test}/${lab}`)!).add(path); }
    }
    const textOnly = [...byLabel.values()].filter((ps) => [...ps].every((q) => q === "$.Error.Message")).length;
    rows.push({ module: m, exact, other, unverified, textOnly, behavioural: Math.max(0, byLabel.size - textOnly), note: "" });
  } finally { server.kill(); }
  const r = rows[rows.length - 1];
  const total = r.exact + r.other + r.unverified;
  console.log(`${m.padEnd(16)} ${String(total).padStart(4)} labels  exact ${String(r.exact).padStart(4)}  wording-only ${String(r.textOnly).padStart(3)}  behavioural ${String(r.behavioural).padStart(3)}  unverified ${String(r.unverified).padStart(3)}  ${r.note}`);
}

const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)}%` : "n/a");
let md = `# Baseline: ${label} against the AWS recordings\n\nGenerated by \`tools/aws-rec/baseline.ts\`. Labels are the harness's compared responses. "Exact" matched what AWS answered; "wording only" differ only in the error message text; "behavioural" differ in status, code, shape or whether the call is refused.\n\n| Module | Labels | Exact | Exact + wording-only | Behavioural | Unverified |\n|---|---|---|---|---|---|\n`;
for (const r of rows) {
  const total = r.exact + r.other + r.unverified;
  md += r.note ? `| ${r.module} | | | | | ${r.note} |\n` : `| ${r.module} | ${total} | ${r.exact} (${pct(r.exact, total)}) | ${pct(r.exact + r.textOnly, total)} | ${r.behavioural} | ${r.unverified} |\n`;
}
await Bun.write(`${root}/docs/port/aws/baseline.md`, md);
console.log(`\nwrote docs/port/aws/baseline.md`);
