// Generates crates/aws-cron/src/zones.rs: every IANA zone name and the POSIX TZ rule it follows today.
//
//   bun tools/gen-tz-rules.ts [/usr/share/zoneinfo] > crates/aws-cron/src/zones.rs
//
// The rule is the footer of the zone's TZif (version 2 or later) file: the text between the last two newlines. A schedule only ever
// asks about the future, and the footer is what the zone does from its last listed transition on, so the footer alone is enough for
// EventBridge Scheduler. This keeps ~15 KB in the binary instead of a whole time zone database (chrono-tz +1.2 MB, jiff's bundled
// tzdb +400 KB, measured 2026-11-14), and gives the same answers on macOS, Linux and Windows (which has no zoneinfo files).

import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2] ?? "/usr/share/zoneinfo";
const skipDirs = new Set(["posix", "right", "Etc/Unknown"]);
const skipFiles = new Set(["Factory", "posixrules", "localtime", "leapseconds", "+VERSION", "SECURITY", "leap-seconds.list"]);

function walk(dir: string, prefix: string, out: string[]) {
  for (const name of readdirSync(dir).sort()) {
    const rel = prefix ? `${prefix}/${name}` : name;
    if (skipDirs.has(rel) || skipFiles.has(name) || name.includes(".")) continue;
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path, rel, out);
    else out.push(rel);
  }
}

function footer(bytes: Buffer): string | null {
  if (bytes.subarray(0, 4).toString("latin1") !== "TZif" || bytes[4] < 0x32) return null;
  const text = bytes.toString("latin1");
  const end = text.lastIndexOf("\n");
  const start = text.lastIndexOf("\n", end - 1);
  if (end < 0 || start < 0) return null;
  return text.slice(start + 1, end);
}

const names: string[] = [];
walk(root, "", names);
const zones: [string, string][] = [];
for (const name of names) {
  const rule = footer(readFileSync(join(root, name)));
  if (rule) zones.push([name, rule]);
}
zones.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
const rules = [...new Set(zones.map(([, r]) => r))].sort();
const version = (() => {
  try {
    return readFileSync(join(root, "+VERSION"), "latin1").trim();
  } catch {
    return "unknown";
  }
})();

const lines: string[] = [];
lines.push(`// @generated by \`bun tools/gen-tz-rules.ts\` from tzdata ${version}; do not edit.`);
lines.push("// Every IANA time zone and the POSIX TZ rule it follows now.");
lines.push("");
lines.push("/// The distinct rules.");
lines.push("pub(crate) const RULES: &[&str] = &[");
for (const r of rules) lines.push(`    ${JSON.stringify(r)},`);
lines.push("];");
lines.push("");
lines.push("/// Zone names in byte order, each with the index of its rule.");
lines.push("pub(crate) const ZONES: &[(&str, u8)] = &[");
for (const [n, r] of zones) lines.push(`    (${JSON.stringify(n)}, ${rules.indexOf(r)}),`);
lines.push("];");
console.log(lines.join("\n"));
