//! `codegen`: deterministic Smithy JSON AST to the packed schema tables.
//!
//! ```text
//! codegen --models models --overlays codegen/overlays --out crates [--check] [--only sqs,ssm]
//! ```
//!
//! Each `models/<name>.json` becomes `<out>/aws-model-<name>/`. With `--check` nothing is written: the
//! generator reports every file that differs from what is on disk and exits non-zero if there is one.

mod emit;
mod ir;
mod model;
mod names;
mod overlay;

use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use sha2::{Digest, Sha256};

use model::Model;
use overlay::Overlay;

struct Args {
    models: PathBuf,
    overlays: PathBuf,
    out: PathBuf,
    check: bool,
    only: Vec<String>,
}

fn main() -> Result<()> {
    let args = parse(std::env::args().skip(1).collect())?;
    let mut stale = Vec::new();
    for stem in stems(&args)? {
        stale.extend(one(&args, &stem)?);
    }
    if args.check && !stale.is_empty() {
        for s in &stale {
            println!("stale: {s}");
        }
        bail!(
            "{} generated file(s) differ from the model: run `cargo xtask codegen`",
            stale.len()
        );
    }
    Ok(())
}

fn parse(argv: Vec<String>) -> Result<Args> {
    let (mut models, mut overlays, mut out) = (None, None, None);
    let (mut check, mut only) = (false, Vec::new());
    let mut it = argv.into_iter();
    while let Some(flag) = it.next() {
        let mut value = || it.next().with_context(|| format!("{flag} needs a value"));
        match flag.as_str() {
            "--models" => models = Some(PathBuf::from(value()?)),
            "--overlays" => overlays = Some(PathBuf::from(value()?)),
            "--out" => out = Some(PathBuf::from(value()?)),
            "--only" => only = value()?.split(',').map(str::to_owned).collect(),
            "--check" => check = true,
            other => bail!("unknown argument {other}"),
        }
    }
    Ok(Args {
        models: models.context("--models is required")?,
        overlays: overlays.context("--overlays is required")?,
        out: out.context("--out is required")?,
        check,
        only,
    })
}

/// The model files to generate, by stem, in name order.
fn stems(args: &Args) -> Result<Vec<String>> {
    let mut stems: Vec<String> = std::fs::read_dir(&args.models)
        .with_context(|| args.models.display().to_string())?
        .filter_map(|e| e.ok()?.path().file_stem()?.to_str().map(str::to_owned))
        .collect();
    stems.sort();
    stems.dedup();
    if !args.only.is_empty() {
        stems.retain(|s| args.only.contains(s));
    }
    Ok(stems)
}

fn sha(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

/// Generates (or checks) one service; returns the files that differ from disk.
fn one(args: &Args, stem: &str) -> Result<Vec<String>> {
    let bytes = std::fs::read(args.models.join(format!("{stem}.json")))?;
    let mut model: Model =
        serde_json::from_slice(&bytes).with_context(|| format!("parsing {stem}"))?;
    let mut header = format!(
        "@generated by `cargo xtask codegen` from models/{stem}.json (sha256 {})",
        &sha(&bytes)[..16]
    );
    let overlay_path = args.overlays.join(format!("{stem}.json"));
    if overlay_path.exists() {
        let ob = std::fs::read(&overlay_path)?;
        Overlay::parse(&ob)?.apply(&mut model)?;
        header.push_str(&format!(
            " and codegen/overlays/{stem}.json (sha256 {})",
            &sha(&ob)[..16]
        ));
    }
    header.push_str("; do not edit.");
    let ir = ir::build(&model)?;
    let name = format!("aws-model-{stem}");
    let rendered = emit::render(&ir, &name, stem, &header)?;
    println!(
        "{name}: {} | {} hand-predicate patterns",
        rendered.counts,
        rendered.hand_patterns.len()
    );
    sync(&args.out.join(&name), &rendered.files, args.check)
}

fn sync(dir: &Path, files: &[(String, String)], check: bool) -> Result<Vec<String>> {
    let mut stale = Vec::new();
    for (rel, text) in files {
        let path = dir.join(rel);
        if std::fs::read_to_string(&path).ok().as_deref() == Some(text.as_str()) {
            continue;
        }
        stale.push(path.display().to_string());
        if !check {
            std::fs::create_dir_all(path.parent().context("no parent")?)?;
            std::fs::write(&path, text)?;
        }
    }
    Ok(if check { stale } else { Vec::new() })
}
