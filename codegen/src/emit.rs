//! Writes one service's crate: the packed tables, the typed keys, the `Operation` enum and the manifest.
//!
//! The output depends only on the model bytes, the overlay bytes and this generator, never on the clock or
//! the environment, so it can be committed, reviewed as a diff, and checked with `--check`.

mod keys;
mod model;
mod words;

use anyhow::Result;

use crate::ir::{Ir, ServiceIr};

/// One generated crate: relative paths with their contents.
#[derive(Debug)]
pub struct Rendered {
    pub files: Vec<(String, String)>,
    pub counts: String,
    /// Model patterns `regex-lite` cannot compile: each needs a hand predicate in `aws-schema` or a recorded reason.
    pub hand_patterns: Vec<String>,
}

/// Renders the crate named `crate_name` for `ir`. `header` is the provenance line every file carries.
pub fn render(ir: &Ir, crate_name: &str, service: &str, header: &str) -> Result<Rendered> {
    let m = model::Model::build(ir)?;
    let tables = m.emit_tables()?;
    let files = vec![
        ("Cargo.toml".to_owned(), manifest(crate_name, service)),
        ("src/lib.rs".to_owned(), lib_rs(service, header)),
        ("src/tables.rs".to_owned(), format!("// {header}\n{tables}")),
        (
            "src/keys.rs".to_owned(),
            format!("// {header}\n{}", m.emit_keys()?),
        ),
        (
            "src/ops.rs".to_owned(),
            format!("// {header}\n{}", m.emit_ops()),
        ),
        (
            "src/meta.rs".to_owned(),
            format!("// {header}\n{}", meta_rs(&ir.service)),
        ),
    ];
    Ok(Rendered {
        files,
        counts: m.counts(),
        hand_patterns: m.hand_patterns.clone(),
    })
}

fn meta_rs(s: &ServiceIr) -> String {
    let protocols: Vec<String> = s
        .protocols
        .iter()
        .map(|p| format!("Protocol::{p:?}"))
        .collect();
    let xml = s
        .xml_namespace
        .as_ref()
        .map_or_else(|| "None".to_owned(), |x| format!("Some({x:?})"));
    format!(
        "use aws_schema::meta::{{Protocol, ServiceMeta}};\n\n\
         pub const META: ServiceMeta = ServiceMeta {{\n    shape_name: {:?},\n    namespace: {:?},\n    signing_name: {:?},\n    \
         sdk_id: {:?},\n    version: {:?},\n    protocols: &[{}],\n    query_compatible: {},\n    xml_namespace: {xml},\n}};\n",
        s.shape_name,
        s.namespace,
        s.signing_name,
        s.sdk_id,
        s.version,
        protocols.join(", "),
        s.query_compatible,
    )
}

fn manifest(crate_name: &str, service: &str) -> String {
    format!(
        "# {HEADER_NOTE}\n[package]\nname = \"{crate_name}\"\nversion = \"0.0.0\"\n\
         description = \"The {service} model as packed schema tables, typed keys and an Operation enum\"\n\
         edition.workspace = true\nlicense.workspace = true\nrepository.workspace = true\n\
         rust-version.workspace = true\npublish.workspace = true\n\n[lints]\nworkspace = true\n\n\
         [dependencies]\naws-schema = {{ path = \"../aws-schema\" }}\n"
    )
}

const HEADER_NOTE: &str = "@generated by `cargo xtask codegen`; do not edit.";

fn lib_rs(service: &str, header: &str) -> String {
    format!(
        "//! The {service} model, generated: packed schema tables ([`tables::TABLES`]), typed member keys\n\
         //! ([`keys`]) and every operation by name ([`ops::Operation`]).\n\
         //!\n//! {header}\n\n\
         #![forbid(unsafe_code)]\n\n\
         // The generated files are tables and constants; their layout is the generator's, not rustfmt's.\n\
         #[rustfmt::skip]\npub mod keys;\n#[rustfmt::skip]\npub mod meta;\n#[rustfmt::skip]\npub mod ops;\n#[rustfmt::skip]\npub mod tables;\n\n\
         pub use ops::Operation;\n"
    )
}
