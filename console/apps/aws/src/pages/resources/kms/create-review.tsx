// Create key, step 6 (kms__key-create-review): what was chosen, each part with its Edit back to its step, and what Finish makes.
import { PencilIcon } from "lucide-react";
import { ReviewSection } from "@doze/ui/components/app/stepper";
import { Button } from "@doze/ui/components/ui/button";
import { filled } from "@doze/ui/components/app/key-values";
import { Note } from "../cfg-parts";
import { type KeyForm, policySent } from "./create-model";
import { parsePolicy, principalWords, statementWords } from "./model";

const KINDS = { symmetric: "Symmetric", asymmetric: "Asymmetric" } as const;
const USAGES: Record<string, string> = { ENCRYPT_DECRYPT: "Encrypt and decrypt", SIGN_VERIFY: "Sign and verify", GENERATE_VERIFY_MAC: "Generate and verify MAC", KEY_AGREEMENT: "Key agreement" };

const names = (arns: readonly string[]) => (arns.length === 0 ? "None" : arns.map((a) => `${principalWords(a).name} ${principalWords(a).kind}`).join(", "));

export function StepReview({ f, account, onEdit }: { f: KeyForm; account: string; onEdit: (step: number) => void }) {
  const tags = filled(f.tags);
  const policy = policySent(f, account);
  const sids = parsePolicy(policy)?.Statement?.map((s) => s.Sid).filter(Boolean) ?? [];
  // The board's one card: every answer in a row, each with a small Edit that goes back to the step it was given on.
  const edit = (value: React.ReactNode, step: number, what: string) => (
    <span className="flex items-start justify-between gap-3">
      <span className="min-w-0">{value}</span>
      <Button type="button" variant="ghost" size="sm" className="-my-1 shrink-0" onClick={() => onEdit(step)} aria-label={`Edit ${what}`} data-testid={`review-edit-${what}`}><PencilIcon /> Edit</Button>
    </span>
  );
  return (
    <>
      <ReviewSection title="Key settings" rows={[
        { label: "Key type", value: edit(KINDS[f.kind], 0, "key settings") },
        { label: "Key usage", value: USAGES[f.usage] ?? f.usage },
        { label: "Key spec", value: <span className="font-mono text-[13px]">{f.spec}</span> },
        { label: "Regionality", value: f.multiRegion ? "Multi-Region key" : "Single-Region key" },
        { label: "Alias", value: edit(<span className="font-mono text-[13px]" data-testid="review-alias">{f.alias}</span>, 1, "labels") },
        { label: "Description", value: f.description || <span className="text-muted-foreground">None</span> },
        { label: "Tags", value: tags.length === 0 ? <span className="text-muted-foreground">None</span> : tags.map((t) => `${t.key}: ${t.value}`).join(" ") },
        { label: "Key administrators", value: edit(<>{names(f.admins)}{f.admins.length > 0 && <span className="mt-0.5 block text-[12.5px] text-muted-foreground">{f.canDelete ? "Administrators can delete this key" : "Administrators cannot delete this key"}</span>}</>, 2, "key administrators") },
        { label: "Key users", value: edit(names(f.users), 3, "key users") },
        { label: "Key policy", value: edit(`${statementWords(policy)}: ${sids.join(", ")}`, 4, "key policy") },
      ]} />
      <Note testId="review-note">The key is created Enabled, with key material generated by KMS, as a {f.multiRegion ? "Multi-Region" : "single-Region"} key. Automatic rotation is off until you turn it on from the key&apos;s Key material and rotations tab.</Note>
    </>
  );
}
