// bun run build (after the typecheck): the Vite build into crates/aws-console/web-dist/, then what the Rust side needs from it
// (crates/aws-console/src/web.rs and its tests):
//   1. a .gz beside every text file (`pack` below); the server serves both kinds through `files::packed` (the gzip as it is,
//      inflated for a client that does not accept it). The plain file stays: a Rust test inflates each .gz against it,
//   2. web-dist/manifest.rs: one include_bytes! entry per file (the .gz where there is one), included by src/web.rs,
//   3. web-dist/source-hash.txt: the hash of the console/ sources (scripts/source-hash.ts), which a Rust test recomputes.
// It fails if index.html carries an inline script or a script file evaluates strings: the console's CSP forbids both.
import { readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { gzipSync } from "node:zlib";
import { sourceHash } from "./source-hash.ts";

const app = join(import.meta.dir, "..");
const consoleDir = join(app, "../..");
const dist = join(consoleDir, "../crates/aws-console/web-dist");

/** The compression every embedded text file gets: level 9 and the largest memory level; the header carries no time, and its
 * operating-system byte is set to 3 (Unix) because zlib writes the build machine's, so the file is the same wherever it is
 * built and a check of the committed bundle holds. */
function pack(bytes: Uint8Array): Uint8Array {
  const out = gzipSync(bytes, { level: 9, memLevel: 9 });
  out[9] = 3;
  return out;
}

const vite = Bun.spawnSync(["bunx", "--bun", "vite", "build", "--logLevel", "warn"], { cwd: app, stdout: "inherit", stderr: "inherit" });
if (vite.exitCode !== 0) process.exit(vite.exitCode ?? 1);
// Vite's own list of the public directory is not needed; nothing else is left behind.
rmSync(join(dist, ".vite"), { recursive: true, force: true });

const TYPES: Record<string, [type: string, text: boolean]> = {
  html: ["text/html; charset=utf-8", true],
  js: ["text/javascript; charset=utf-8", true],
  css: ["text/css; charset=utf-8", true],
  svg: ["image/svg+xml", true],
  json: ["application/json", true],
  txt: ["text/plain; charset=utf-8", true],
  woff2: ["font/woff2", false],
  png: ["image/png", false],
};

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path, out);
    else out.push(relative(dist, path).split(sep).join("/"));
  }
  return out;
}

const problems: string[] = [];
const files = walk(dist).filter((f) => !f.endsWith(".gz") && f !== "manifest.rs" && f !== "source-hash.txt").sort();
const entries: string[] = [];
let raw = 0;
let embedded = 0;
for (const rel of files) {
  const ext = rel.split(".").pop() ?? "";
  const kind = TYPES[ext];
  if (!kind) {
    problems.push(`${rel}: no content type for .${ext}`);
    continue;
  }
  const [type, text] = kind;
  const bytes = readFileSync(join(dist, rel));
  raw += bytes.length;
  if (ext === "html" && /<script(?![^>]*\bsrc=)[^>]*>/i.test(bytes.toString())) problems.push(`${rel}: an inline <script> (the CSP forbids it)`);
  if (ext === "js" && /\beval\(|new Function\(/.test(bytes.toString())) problems.push(`${rel}: evaluates a string (the CSP forbids it)`);
  let path = rel;
  if (text) {
    const gz = pack(bytes);
    writeFileSync(join(dist, `${rel}.gz`), gz);
    embedded += gz.length;
    path = `${rel}.gz`;
  } else embedded += bytes.length;
  // The shape rustfmt gives the entry, so `cargo fmt` leaves the file as it was written.
  entries.push(
    [
      "    (",
      `        ${JSON.stringify(rel)},`,
      "        Served {",
      `            content_type: ${JSON.stringify(type)},`,
      "            bytes: include_bytes!(concat!(",
      '                env!("CARGO_MANIFEST_DIR"),',
      `                ${JSON.stringify(`/web-dist/${path}`)}`,
      "            )),",
      `            gzip: ${text},`,
      "        },",
      "    ),",
    ].join("\n"),
  );
}
if (!files.includes("index.html")) problems.push("index.html: the build wrote none");
if (problems.length) {
  for (const p of problems) console.error(`embed: ${p}`);
  process.exit(1);
}
writeFileSync(
  join(dist, "manifest.rs"),
  `// @generated by console/apps/aws/scripts/embed.ts (bun run build in console/apps/aws). Do not edit.\n\n/// Every file of the bundle.\npub const FILES: &[(&str, Served)] = &[\n${entries.join("\n")}\n];\n`,
);
writeFileSync(join(dist, "source-hash.txt"), `${sourceHash(consoleDir)}\n`);
console.log(`web-dist: ${files.length} files, ${(raw / 1024).toFixed(1)} KiB raw, ${(embedded / 1024).toFixed(1)} KiB embedded, source hash ${sourceHash(consoleDir)}`);
